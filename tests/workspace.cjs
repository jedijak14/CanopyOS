const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM, VirtualConsole } = require('jsdom');
const html = fs.readFileSync('index.html', 'utf8').replace('<script src="vendor/holidays.min.js"></script>', () => '<script>' + fs.readFileSync('vendor/holidays.min.js', 'utf8') + '</script>');
const errors = [];
const consoleCapture = new VirtualConsole();
consoleCapture.on('jsdomError', e => errors.push(e.message));
consoleCapture.on('error', (...args) => errors.push(args.join(' ')));
const dom = new JSDOM(html, {
  url: 'https://canopy.test/', runScripts: 'dangerously', pretendToBeVisual: true, virtualConsole: consoleCapture,
  beforeParse(w) {
    w.matchMedia = () => ({ matches: false, addEventListener() {} });
    w.fetch = async () => ({ ok: true, json: async () => ({ current: {temperature_2m: 60, weather_code: 63, is_day: 1, apparent_temperature: 59, relative_humidity_2m: 70, wind_speed_10m: 4}, daily: {time:['2026-11-02'], temperature_2m_min:[50], temperature_2m_max:[65], weather_code:[63]}, hourly: {time:['2026-11-02T12:00'], temperature_2m:[60], weather_code:[63]}}) });
    w.navigator.getBattery = async () => ({level:.42, charging:true});
    w.navigator.geolocation = {getCurrentPosition: success => success({coords:{latitude:32.7, longitude:-117.1}})};
  }
});
const w = dom.window;
const run = expression => w.eval(expression);
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
(async () => {
  await wait(50);
  assert.equal(run('OS.phase'), 'login', 'first-run login appears immediately');
  assert.ok(w.document.querySelector('.login-form'), 'first-run profile form appears without a boot delay');
  assert.equal(run('DEFAULT_SETTINGS.dockAutoHide'), false, 'Dock auto-hide is opt-in');
  run(`bootTimers.forEach(clearTimeout); signIn(Users.create({name:'Tester',password:'',avatar:'🌿',color:'#34d399'})); setPhase('desktop'); renderDesktop();`);
  const apps = run('Object.keys(APPS)');
  for (const app of apps) {
    const id = run(`openApp(${JSON.stringify(app)})`);
    const win = run(`OS.windows.find(x => x.id === ${JSON.stringify(id)})`);
    const original = {x:win.x, y:win.y, w:win.w, h:win.h};
    w.document.querySelector(`#win-${id} [aria-label="Enter or exit full screen"]`).click();
    assert.equal(win.maximized, true, app);
    assert.equal(win.x, 0, app); assert.equal(win.y, 30, app);
    assert.equal(win.w, w.innerWidth, app); assert.equal(win.h, w.innerHeight - 30, app);
    assert.ok(w.document.querySelector(`#win-${id}`).classList.contains('is-full'), app);
    w.document.querySelector(`#win-${id} [aria-label="Enter or exit full screen"]`).click();
    assert.equal(win.maximized, false, app);
    assert.deepEqual({x:win.x, y:win.y, w:win.w, h:win.h}, original, app);
  }
  assert.equal(errors.filter(e => e.includes('app crashed')).length, 0, errors.join('\n'));
  run(`openApp('notes', {newNote:true})`);
  const notesBefore = run(`Notes.all(OS.user.id).length`);
  run(`openApp('notes')`);
  assert.equal(run(`Notes.all(OS.user.id).length`), notesBefore, 'reopening notes must not create another note');
  w.document.querySelector('[aria-label="Duplicate note"]').click();
  assert.equal(run(`Notes.all(OS.user.id).length`), notesBefore + 1, 'duplicate creates a separate note');
  let downloadName = '';
  w.URL.createObjectURL = () => 'blob:test'; w.URL.revokeObjectURL = () => {};
  w.HTMLAnchorElement.prototype.click = function () { downloadName = this.download; };
  w.document.querySelector('[aria-label="Export as text"]').click();
  assert.match(downloadName, /\.txt$/);
  run(`openApp('reminders')`);
  const form = w.document.querySelector('.reminder-form');
  form.querySelector('[type=text]').value = 'Buy groceries';
  form.querySelector('[type=date]').value = '2026-11-02';
  form.dispatchEvent(new w.Event('submit', {bubbles:true, cancelable:true}));
  assert.equal(run(`store.get('reminders.'+OS.user.id, []).length`), 1);
  w.document.querySelector('.reminder-row [data-edit]').click();
  form.querySelector('[type=text]').value = 'Buy milk';
  form.dispatchEvent(new w.Event('submit', {bubbles:true, cancelable:true}));
  assert.equal(run(`store.get('reminders.'+OS.user.id, [])[0].title`), 'Buy milk');
  w.document.querySelector('.reminder-row input').click();
  assert.equal(run(`store.get('reminders.'+OS.user.id, [])[0].done`), true);
  w.document.querySelectorAll('.reminder-filters button')[3].click();
  assert.match(w.document.querySelector('.reminder-list').textContent, /Buy milk/);
  w.document.querySelector('.reminder-row [data-delete]').click();
  assert.equal(run(`store.get('reminders.'+OS.user.id, []).length`), 0);
  run(`toggleMissionControl(true)`);
  assert.equal(w.document.querySelectorAll('.mission-card').length, apps.length);
  w.document.querySelector('.mission-card').click();
  run(`toggleShowDesktop()`); assert.equal(run(`OS.windows.filter(x => !x.minimized && !x.closing).length`), 0);
  run(`toggleShowDesktop()`); assert.equal(run(`OS.windows.filter(x => !x.minimized && !x.closing).length`), apps.length);
  run(`updateSettings({dockAutoHide:true}); updateSettings({clock24:true})`);
  assert.ok(w.document.querySelector('#dock').classList.contains('auto-hide'));
  await wait(750);
  run(`updateSettings({theme:'light'})`); await wait(750);
  assert.equal(run(`Users.byId(OS.user.id).settings.dockAutoHide`), true);
  assert.equal(run(`Users.byId(OS.user.id).settings.clock24`), true);
  assert.equal(run(`Users.byId(OS.user.id).settings.theme`), 'light');
  run(`openApp('calendar')`);
  const calendarForm = w.document.querySelector('.cal-add');
  calendarForm.querySelector('input').value = 'Planning';
  calendarForm.dispatchEvent(new w.Event('submit', {bubbles:true,cancelable:true}));
  w.document.querySelector('[aria-label="Edit Planning"]').click();
  calendarForm.querySelector('input').value = 'Planning updated';
  calendarForm.dispatchEvent(new w.Event('submit', {bubbles:true,cancelable:true}));
  assert.equal(run(`OS.settings.events[0].title`), 'Planning updated');
  const ics = run(`exportCalendar([{id:'one', date:'2026-11-02', title:'Hello, world; hi'}])`);
  assert.match(ics, /BEGIN:VCALENDAR/); assert.ok(ics.includes('SUMMARY:Hello\\, world\\; hi'));
  run(`toggleLauncher(true)`); assert.equal(w.document.querySelectorAll('.launch-app').length, apps.length);
  const search = w.document.querySelector('#launcher input'); search.value = 'activity'; search.dispatchEvent(new w.Event('input'));
  assert.equal(w.document.querySelectorAll('.launch-app').length, 1);
  w.document.querySelector('.launch-app').click(); assert.equal(run('OS.activeApp'), 'monitor');
  run(`OS.toasts = []; renderToasts(); notify({title:'Test notification',body:'Hello'}); notify({title:'Another'});`);
  assert.equal(w.document.querySelectorAll('#toasts .toast').length, 2);
  run(`ccState.dnd = true; notify({title:'Quiet notification'}); toggleNotifications(true)`);
  assert.equal(w.document.querySelectorAll('#toasts .toast').length, 2);
  assert.match(w.document.querySelector('#notification-center').textContent, /Quiet notification/);
  w.document.querySelector('#notification-center [data-clear]').click();
  assert.match(w.document.querySelector('#notification-center').textContent, /No notifications/);
  run(`toggleMaximize(OS.activeId)`);
  Object.defineProperty(w, 'innerWidth', {value: 800, configurable:true});
  Object.defineProperty(w, 'innerHeight', {value: 600, configurable:true});
  w.dispatchEvent(new w.Event('resize'));
  assert.equal(run('OS.windows.find(x=>x.id===OS.activeId).w'), 800);
  assert.equal(run('OS.windows.find(x=>x.id===OS.activeId).h'), 570);
  run(`tileWindow(OS.activeId, 'left')`);
  assert.equal(run('OS.windows.find(x=>x.id===OS.activeId).x'), 8);
  run(`ccState.dnd = false; store.set('notifications.' + OS.user.id, []); store.set('reminders.' + OS.user.id, [{id:'due',title:'Due now',date:'2020-01-01',time:'09:00',done:false}]); checkDueReminders(); checkDueReminders();`);
  assert.equal(run(`store.get('notifications.' + OS.user.id, []).filter(x => x.body === 'Due now').length`), 1, 'timed reminder only fires once');
  assert.equal((await run(`fernLocal('what is my battery')`)).reply, 'Your battery is at 42% and charging.');
  assert.match((await run(`fernLocal('where am i')`)).reply, /updated Weather/);
  run(`updateSettings({wallpaper:'weather'})`); await wait(500);
  assert.ok(w.document.querySelector('#bg-wall').classList.contains('weather-rain'));
  assert.equal(w.document.querySelectorAll('#holiday-country option').length > 200, true);
  // Fern and Clock share persistent, deadline-based timers and live views.
  run(`openApp('fern'); openApp('clock', {tab:'timer'});`);
  const fernInput = w.document.querySelector('.fern-app input');
  fernInput.value = 'set a timer for 2 minutes and 3 seconds called tea';
  fernInput.closest('form').dispatchEvent(new w.Event('submit', {bubbles:true, cancelable:true}));
  await wait(30);
  assert.equal(run(`Timers.active().length`), 1);
  assert.equal(run(`Timers.active()[0].label`), 'tea');
  assert.equal(run(`Timers.active()[0].total`), 123000, 'compound durations are parsed');
  const teaId = run(`Timers.active()[0].id`);
  const shelfTimer = () => w.document.querySelector(`.fern-timer-shelf [data-live-timer="${teaId}"]`);
  const clockTimer = () => w.document.querySelector(`.clock-timer-list [data-live-timer="${teaId}"]`);
  assert.ok(shelfTimer()); assert.ok(clockTimer());
  assert.ok(w.document.querySelector(`.fern-scroll [data-live-timer="${teaId}"]`), 'reply contains a live timer card');
  const firstShown = shelfTimer().querySelector('.timer-live-time').textContent;
  fernInput.value = 'draft message';
  await wait(1200);
  assert.notEqual(shelfTimer().querySelector('.timer-live-time').textContent, firstShown, 'Fern countdown advances');
  assert.equal(clockTimer().querySelector('.timer-live-time').textContent, shelfTimer().querySelector('.timer-live-time').textContent);
  assert.equal(fernInput.value, 'draft message', 'timer ticks do not disturb input');
  clockTimer().querySelector('[data-timer-toggle]').click();
  assert.equal(run(`Timers.get(${JSON.stringify(teaId)}).state`), 'paused');
  assert.equal(shelfTimer().querySelector('.timer-live-status').textContent, 'Paused');
  const paused = run(`Timers.remaining(Timers.get(${JSON.stringify(teaId)}))`);
  await wait(300); assert.equal(run(`Timers.remaining(Timers.get(${JSON.stringify(teaId)}))`), paused);
  const resume = await run(`fernLocal('resume tea timer')`);
  assert.match(resume.reply, /Resumed/);
  assert.equal(clockTimer().querySelector('.timer-live-status').textContent, 'Running');
  const status = await run(`fernLocal('how much time is left on the tea timer')`);
  assert.match(status.reply, /tea timer has/);
  assert.match((await run(`fernLocal('cancel missing timer')`)).reply, /couldn't find/);
  assert.equal(run(`Timers.get(${JSON.stringify(teaId)}).state`), 'running');
  const timerForm = w.document.querySelector('.clock-timer-form');
  timerForm.elements.namedItem('m').value = '0'; timerForm.elements.namedItem('m').dispatchEvent(new w.Event('input'));
  timerForm.elements.namedItem('s').value = '10'; timerForm.elements.namedItem('s').dispatchEvent(new w.Event('input'));
  timerForm.elements.namedItem('label').value = 'Coffee';
  timerForm.dispatchEvent(new w.Event('submit', {bubbles:true, cancelable:true}));
  assert.equal(run(`Timers.active().length`), 2);
  assert.match(shelfTimer().parentElement.textContent, /Coffee/);
  assert.match((await run(`fernLocal('pause coffee timer')`)).reply, /Paused/);
  assert.equal(run(`Timers.active()[0].state`), 'paused');
  assert.match((await run(`fernLocal('cancel all timers')`)).reply, /Cancelled 2 timers/);
  assert.equal(run(`Timers.active().length`), 0);
  assert.match((await run(`fernLocal('set a timer for 0 seconds')`)).reply, /one second/);
  assert.match((await run(`fernLocal('set a timer for 25 hours')`)).reply, /24 hours/);
  run(`store.set('notifications.' + OS.user.id, []); window.__finished = setTimer(1, 'Once'); window.__cancelled = setTimer(1, 'Never'); Timers.cancel(window.__cancelled.id); window.__finished.end = Date.now()-1; Timers.tick(); Timers.tick();`);
  assert.equal(run(`store.get('notifications.' + OS.user.id, []).filter(x => x.title === 'Once').length`), 1);
  assert.equal(run(`store.get('notifications.' + OS.user.id, []).filter(x => x.title === 'Never').length`), 0);
  run(`window.__savedTimer = setTimer(60,'Saved'); Timers.pause(window.__savedTimer.id);`);
  run(`closeWindow(OS.windows.find(x=>x.app==='fern').id); closeWindow(OS.windows.find(x=>x.app==='clock').id);`);
  await wait(250);
  run(`openApp('fern'); openApp('clock',{tab:'timer'});`);
  assert.match(w.document.querySelector('.fern-timer-shelf').textContent, /Saved/);
  assert.match(w.document.querySelector('.clock-timer-list').textContent, /Saved/);
  const savedUser = run(`OS.user.id`), savedId = run(`window.__savedTimer.id`);
  run(`resetDesktop();`); await wait(250);
  run(`signIn(Users.byId(${JSON.stringify(savedUser)})); setPhase('desktop'); renderDesktop(); Timers.tick();`);
  assert.equal(run(`Timers.get(${JSON.stringify(savedId)}).state`), 'paused', 'timer survives logout and resumes for its profile');
  run(`window.__otherUser = Users.create({name:'Other',password:'',avatar:'🌿',color:'#34d399'}); resetDesktop(); signIn(window.__otherUser); setPhase('desktop'); renderDesktop();`);
  assert.equal(run(`Timers.active().length`), 0, 'other profiles do not see saved timers');
  run(`resetDesktop(); signIn(Users.byId(${JSON.stringify(savedUser)})); setPhase('desktop'); renderDesktop();`);
  assert.equal(run(`Timers.get(${JSON.stringify(savedId)}).state`), 'paused');

  // Reload with an existing session must enter the desktop immediately and fire an expired timer once.
  run(`window.__reloaded = setTimer(20, 'Reloaded'); window.__reloaded.end = Date.now()-1; Timers.save();`);
  const storage = Object.fromEntries(Object.keys(w.localStorage).map(key => [key, w.localStorage.getItem(key)]));
  const restored = new JSDOM(html, {
    url:'https://canopy.test/', runScripts:'dangerously', pretendToBeVisual:true, virtualConsole:consoleCapture,
    beforeParse(win) {
      Object.entries(storage).forEach(([key,value]) => win.localStorage.setItem(key,value));
      win.matchMedia = () => ({matches:false, addEventListener(){}});
      win.fetch = w.fetch;
    }
  });
  await wait(50);
  assert.equal(restored.window.eval('OS.phase'), 'desktop', 'existing session skips opening sequence');
  assert.equal(restored.window.eval(`store.get('notifications.' + OS.user.id, []).filter(x=>x.title==='Reloaded').length`), 1);
  restored.window.eval('Timers.tick()');
  assert.equal(restored.window.eval(`store.get('notifications.' + OS.user.id, []).filter(x=>x.title==='Reloaded').length`), 1);
  restored.window.close();
  run(`updateSettings({dockSize:66}); resetDesktop()`);
  assert.equal(run(`Users.all()[0].settings.dockSize`), 66, 'pending settings are flushed at logout');
  assert.equal(run(`Users.all()[0].settings.clock24`), true);
  assert.deepEqual(errors, []);
  console.log(`Workspace smoke test passed for ${apps.length} apps.`);
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => dom.window.close());
